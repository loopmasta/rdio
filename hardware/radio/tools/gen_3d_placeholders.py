"""Writes simple 3D placeholder models (VRML, mm) into hardware/radio/rdio.3dshapes/:
  ESP32_DevKit_38pin_Sockets.wrl : two 1x19 pin headers (5 mm high) soldered to the carrier with their solder pins, the DevKit's own 2.5 mm
                                   sockets plugged onto them, the ESP32 DevKit below them
                                   (component side down: module, antenna end and USB-C hang below the DevKit board)
  DRA818_SA818.wrl               : the SA818S module (35.6 x 19 x 3.2 mm) on the top side
Frame = footprint frame: DevKit centre at x=0,y=0, antenna end -x, USB end +x; z=0 is the carrier's top surface, the carrier is 1.6 mm thick.
Usage: python3 -I hardware/radio/tools/gen_3d_placeholders.py   (edit GAP etc. below, then rebuild with make_pcb.sh --install)
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__)); OUT = os.path.join(HERE, "..", "rdio.3dshapes")
PCB_T = 1.6          # carrier thickness
HEADER_H = 5.0       # pin header soldered to the carrier
SOCKET_H = 2.5       # socket built into the DevKit, plugged onto the header
GAP = HEADER_H + SOCKET_H   # free space between the carrier's bottom face and the DevKit board (7.5 mm, measured on the real DevKit)
ROW = 22.86          # distance of the two header rows
KIT_L, KIT_W, KIT_T = 48.26, 25.4, 1.6

def mat(c): return f"appearance Appearance {{ material Material {{ diffuseColor {c[0]} {c[1]} {c[2]} specularColor 0.3 0.3 0.3 shininess 0.3 }} }}"
def box(out, cx, cy, cz, dx, dy, dz, c):
    out.append(f"Transform {{ translation {cx:.3f} {cy:.3f} {cz:.3f} children Shape {{ {mat(c)} geometry Box {{ size {dx:.3f} {dy:.3f} {dz:.3f} }} }} }}")

BLACK=(0.08,0.08,0.08); GOLD=(0.85,0.70,0.20); BLUE=(0.05,0.07,0.12); SILVER=(0.78,0.78,0.80); DARK=(0.03,0.03,0.03); GREY=(0.22,0.22,0.24); GREEN=(0.06,0.25,0.12)

# ---- DevKit on its two headers
o = ["#VRML V2.0 utf8", f"# ESP32 DevKit below the carrier on {HEADER_H} mm headers and its own {SOCKET_H} mm sockets (placeholder shapes, generated by tools/gen_3d_placeholders.py)"]
for sgn in (-1, 1):
    box(o, 0, sgn*ROW/2, -PCB_T - HEADER_H/2, KIT_L, 2.54, HEADER_H, BLACK)       # pin header housing
    box(o, 0, sgn*ROW/2, -PCB_T - HEADER_H - SOCKET_H/2, KIT_L, 2.54, SOCKET_H, GREY)   # the DevKit's socket
    for i in range(19):                                                           # solder pins through the carrier
        box(o, -22.86 + 2.54*i, sgn*ROW/2, -0.25, 0.64, 0.64, 3.5, GOLD)
zk = -PCB_T - GAP - KIT_T/2                                                       # DevKit board centre
box(o, 0, 0, zk, KIT_L, KIT_W, KIT_T, BLUE)
zb = zk - KIT_T/2                                                                 # DevKit underside (component side)
box(o, -8.13, 0, zb - 1.55, 19.0, 18.0, 3.1, SILVER)                              # ESP32 module shield
box(o, -20.88, 0, zb - 0.4, 6.5, 18.0, 0.8, DARK)                                 # antenna end of the module
box(o, 21.45, 0, zb - 1.6, 7.3, 8.94, 3.2, SILVER)                                # USB-C connector
open(os.path.join(OUT, "ESP32_DevKit_38pin_Sockets.wrl"), "w").write("\n".join(o) + "\n")

# ---- SA818S module on the top side
o = ["#VRML V2.0 utf8", "# SA818S module 35.6 x 19 x 3.2 mm (placeholder shapes)"]
box(o, 0, 0, 0.4, 35.6, 19.0, 0.8, GREEN)                                         # module PCB
box(o, 0, 0, 2.0, 35.0, 18.4, 2.4, SILVER)                                        # shield
open(os.path.join(OUT, "DRA818_SA818.wrl"), "w").write("\n".join(o) + "\n")
print("written to", os.path.abspath(OUT))
